import { mkdir, writeFile } from "node:fs/promises";
import { test, expect } from "@playwright/test";
import { STARTER, openProject, ready, replaceSource } from "./helpers";

test.use({ launchOptions: { args: ["--auto-select-tab-capture-source-by-title=Page host", "--allow-http-screen-capture", "--enable-usermedia-screen-capturing"] } });

test("comment selection, host screenshot, pin recovery, and sidecar persistence", async ({ page }) => {
  const source = 'import { Button } from "@flanksource/clicky-ui"; export default function ReviewPage() { return <main className="p-8"><h1>Review heading</h1><Button>Review action</Button></main>; }';
  await openProject(page, { ...STARTER, files: { ...STARTER.files, [STARTER.entry]: source } });
  await ready(page);
  const frame = page.frameLocator('iframe[title="Page preview"]');
  await page.getByRole("button", { name: "Comment on element", exact: true }).click();
  const action = frame.getByRole("button", { name: "Review action", exact: true });
  await expect(action).toBeVisible();
  const target = await action.boundingBox();
  if (!target) throw new Error("Review action has no visible bounds");
  await page.mouse.click(target.x + target.width / 2, target.y + target.height / 2);
  const selected = page.getByTestId("comment-selection");
  await expect(selected).toContainText(/diagram\.tsx:\d+:\d+/);
  await expect(selected).toContainText("Button");
  await page.getByRole("button", { name: "Capture selection", exact: true }).click();
  const screenshot = page.getByRole("img", { name: "Selection screenshot", exact: true });
  await expect(screenshot).toBeVisible({ timeout: 15000 });
  const png = await screenshot.getAttribute("src");
  expect(png).toMatch(/^data:image\/png;base64,/);
  await mkdir("results", { recursive: true });
  await writeFile("results/page-host-comment-selection.png", new Uint8Array(Buffer.from(png!.split(",")[1]!, "base64")));
  await selected.getByRole("textbox").fill("Check the action label");
  await selected.getByRole("button", { name: "Post comment", exact: true }).click();
  await expect(page.getByTestId("comment-thread-block")).toContainText("Check the action label");
  await expect(frame.locator("[data-page-agent]").getByRole("button", { name: /Open 1 comments/ })).toBeVisible();
  await replaceSource(page, source.replace('<main className="p-8">', '<main className="p-8"><p>Inserted before the action</p>'));
  await ready(page);
  await expect(page.getByTestId("comment-anchor-state")).toHaveText(/^(found|moved)$/);
  await expect(frame.locator("[data-page-agent]").getByRole("button", { name: /Open 1 comments/ })).toBeVisible();
  const iframe = page.locator('iframe[title="Page preview"]');
  expect(await iframe.getAttribute("allow") ?? "").not.toMatch(/display-capture|clipboard-write/);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export HTML", exact: true }).click();
  const exported = await (await download).createReadStream();
  if (!exported) throw new Error("HTML snapshot stream is unavailable");
  let html = ""; for await (const chunk of exported) html += chunk.toString();
  expect(html).not.toContain("data-page-agent");
  await page.getByRole("button", { name: "Save to URL", exact: true }).click();
  await page.reload(); await ready(page);
  await page.getByRole("button", { name: "Comments (1)", exact: true }).click();
  await expect(page.getByTestId("comment-thread-block")).toContainText("Check the action label");
  await expect(page.getByRole("img", { name: "Comment screenshot", exact: true })).toBeVisible();
  await writeFile("results/page-host-comment.json", JSON.stringify({ chromium: "native current-tab capture and host crop passed", firefox: "Unverified: current-tab capture handles unavailable", webkit: "Unverified: current-tab capture handles unavailable", pinAfterEdit: await page.getByTestId("comment-anchor-state").textContent() }, null, 2));
});
