import { resolve } from "node:path";
import type { MiddlewareApp } from "./middleware";
import type { SourceRoot } from "./source-roots";
import { configureComments } from "./comments-client";
import { registerCommentsMiddleware } from "./comments-server";
import { createAgentRuns, registerAgentRunsMiddleware } from "./agent-runs-server";
import { createPromptRuns, registerPromptRunsMiddleware } from "./prompt-runs-server";
import { registerNavigationMiddleware } from "./navigation-server";
import { registerSourcesMiddleware, type SourceEvents } from "./sources-server";
import { registerVisualEditsMiddleware } from "./visual-edits-server";
import { registerExportsMiddleware } from "./exports-server";
import { registerGavelLintMiddleware } from "./gavel-lint-server";
import { registerBlameMiddleware } from "./blame-server";
import { registerConnectionsMiddleware } from "./connections-server";
import { registerRuntimeProfilesMiddleware } from "./runtime-profiles-server";
import { registerWorkspaceFilesMiddleware } from "./workspace-files-server";
import { authorizeDocumentDirectory, registerRepositoryDocumentsMiddleware } from "./repository-documents-server";
import { registerBookmarkletMiddleware } from "./bookmarklet-middleware";
import { registerPageActivityMiddleware } from "./page-activity";
import { registerVocabulariesMiddleware } from "./vocabularies-server";
import { fixedGavel, onDemandGavel } from "./gavel-launch-server";

export function registerProductionApi(options: { root: string; middlewares: MiddlewareApp; env: Record<string, string>; sourceRoots: SourceRoot[]; vocabularyRoots: string[]; script: string; events: SourceEvents }) {
  const { root, env, middlewares } = options;
  const workspaceRoot = resolve(root, "../..");
  const dir = resolve(root, ".playground");
  const pagesDir = resolve(root, "src/pages");
  const endpoint = env.PLAYGROUND_GAVEL_URL ? fixedGavel(env.PLAYGROUND_GAVEL_URL) : onDemandGavel({ workspace: workspaceRoot, command: [env.PLAYGROUND_GAVEL_BINARY ?? "gavel"], localRoots: [workspaceRoot, ...(env.PLAYGROUND_LOCAL_ROOTS ?? "").split(",").filter(Boolean)] });
  configureComments({ dir, endpoint, workspace: workspaceRoot });
  const logger = { error: (message: string) => process.stderr.write(message + "\n") };
  const captainURL = env.PLAYGROUND_CAPTAIN_URL ?? "http://localhost:9020";
  const runs = createAgentRuns({ dir, captainURL, cwd: workspaceRoot, skillPath: resolve(workspaceRoot, ".agents/skills/clicky-ui-playground/SKILL.md"), resolveDocumentDirectory: page => authorizeDocumentDirectory({ dir, endpoint, page }) });
  const prompts = createPromptRuns({ dir, endpoint, workspace: workspaceRoot, onCreated: runs.autoRunComment });
  const app = { middlewares, dir, pagesDir, logger };
  const closeVocabularies = registerVocabulariesMiddleware({ ...app, roots: options.vocabularyRoots, sourceRoots: options.sourceRoots });
  registerAgentRunsMiddleware({ ...app, runs });
  registerPromptRunsMiddleware({ ...app, runs: prompts });
  const navigation = registerNavigationMiddleware({ ...app, endpoint, problems: prompts.problems, metadataRoots: options.sourceRoots.map(root => root.directory) });
  registerCommentsMiddleware({ ...app, onCreated: runs.autoRunComment });
  registerRepositoryDocumentsMiddleware({ ...app, endpoint });
  registerBookmarkletMiddleware({ ...app, script: () => options.script });
  registerSourcesMiddleware({ ...app, commentsDir: dir, workspaceRoot, events: options.events });
  registerVisualEditsMiddleware({ ...app, workspaceRoot, changed: options.events.changed });
  registerExportsMiddleware(app);
  registerGavelLintMiddleware({ ...app, workspaceRoot, promptFile: resolve(root, "prompts/markdown-review.prompt") });
  registerBlameMiddleware({ ...app, cwd: workspaceRoot });
  registerConnectionsMiddleware({ ...app, gavel: endpoint, captainURL });
  registerRuntimeProfilesMiddleware({ ...app, modelsURL: `${captainURL}/api/chat/models`, permissionsURL: `${captainURL}/api/captain/ai/permissions/catalog`, runtimesURL: `${captainURL}/api/chat/runtimes`, resolveURL: `${captainURL}/api/chat/runtime-profiles/resolve`, presetsResolveURL: `${captainURL}/api/chat/runtime-presets/resolve` });
  registerWorkspaceFilesMiddleware({ ...app, cwd: workspaceRoot });
  registerPageActivityMiddleware(app);
  return { changed: () => navigation.clearMeta(), async close() { closeVocabularies(); prompts.close(); await endpoint.close(); } };
}
