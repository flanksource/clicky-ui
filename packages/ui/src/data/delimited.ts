/** The field delimiter of each fenced-code language that renders as a table. */
export const DELIMITED_LANGUAGES: Record<string, string> = { csv: ",", tsv: "\t" };

/**
 * Parses RFC 4180 delimited text into rows: quoted fields may hold the
 * delimiter, newlines and `""` escapes. A trailing newline does not add an
 * empty row. An unterminated quote throws, rather than rendering a table that
 * silently swallowed the rest of the text.
 */
export function parseDelimited(text: string, delimiter = ","): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"' && field === "") quoted = true;
    else if (c === delimiter) {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (quoted) throw new Error("CSV: unterminated quoted field");
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}
